/**
 * 金意陶产品目录 —— 6 大系列的 36 个代表性 SKU。
 *
 * 图片来源：100% 来自 kito.cn 官方 CDN —— 端点
 *   https://www.kito.cn/kitocms/webapi/at/getProductSeries
 * 返回每个系列的 6 个代表性图片资源（banner、enter、space、
 * texture、m-banner、m-enter）。全部下载并自托管于
 *   /img/products/kito/{series-slug}-{kind}.{ext}
 *
 * **重要说明：** SPA `kito.cn/product.html` 不暴露单个 SKU 的 API
 * —— 仅返回系列。因此：
 *   • 系列名称 + 标语（define）：来自金意陶 API（100% 准确）
 *   • 各系列的 banner/enter/space/texture 图片：来自金意陶 API（真实）
 *   • SKU 代码 + SKU 名称 + 参数：综合金意陶在天猫/京东公布的目录
 *     + 瓷砖行业知识；系列内每个 SKU 以系列图片轮换作缩略图
 *     （gallery 含 3 个不同视角 —— texture、空间、banner）。
 *
 * 当广州采购获取到含各 SKU 单独图片的金意陶 PDF 目录后，
 * 替换每个条目的 `image` + `gallery` 字段。
 */

/** 辅助函数：为 1 个系列排布图片 —— 6 个 SKU 轮换 4 个主视图。 */
function seriesImages(slug: string) {
  const base = `/img/products/kito/${slug}`;
  // 检测 texture 扩展名（wood-grain 用 .jpg，其他系列用 .png）
  const textureExt = slug === "wood-grain" ? "jpg" : "png";
  return {
    texture: `${base}-texture.${textureExt}`,
    space: `${base}-space.png`,
    banner: `${base}-banner.jpg`,
    enter: `${base}-enter.jpg`,
    mBanner: `${base}-m-banner.jpg`,
    mEnter: `${base}-m-enter.${slug === "classic-candy" || slug === "stone-glaze" ? "jpg" : "png"}`,
  };
}

