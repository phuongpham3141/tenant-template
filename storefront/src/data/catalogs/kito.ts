/**
 * KITO catalog — 36 representative SKUs across 6 series.
 *
 * Image source: 100% from the official kito.cn CDN — the endpoint
 *   https://www.kito.cn/kitocms/webapi/at/getProductSeries
 * returns 6 representative image assets per series (banner, enter, space,
 * texture, m-banner, m-enter). All are downloaded and self-hosted under
 *   /img/products/kito/{series-slug}-{kind}.{ext}
 *
 * Important note: the kito.cn/product.html SPA does not expose an API
 * for individual SKUs — it only returns series. Therefore:
 *   - Series name + tagline (define): from the KITO API (100% accurate)
 *   - Per-series banner/enter/space/texture images: from the KITO API (real)
 *   - SKU codes + SKU names + specs: compiled from the KITO catalog published
 *     on Tmall/JD + ceramic industry knowledge; each SKU in a series
 *     uses rotated series images as thumbnails (the gallery has 3 different
 *     viewpoints — texture, space, banner).
 *
 * Once Guangzhou sourcing obtains the KITO PDF catalog with per-SKU images,
 * swap the image and gallery fields on each entry.
 */

/** Helper that arranges images for one series — 6 SKUs rotated across 4 main views. */
function seriesImages(slug: string) {
  const base = `/img/products/kito/${slug}`;
  // Detect texture extension (wood-grain uses .jpg, other series use .png)
  const textureExt = slug === "wood-grain" ? "jpg" : "png";
  return {
    texture: `${base}-texture.${textureExt}`,
    space: `${base}-space.png`,
    banner: `${base}-banner.jpg`,
    enter: `${base}-enter.jpg`,
    mBanner: `${base}-m-banner.jpg`,
    mEnter: `${base}-m-enter.${slug === "classic-candy" || slug === "stone-glaze" ? "jpg" : "png"}`,
  };
}

const IMG = {
  candy: seriesImages("classic-candy"),
  stone: seriesImages("stone-glaze"),
  art: seriesImages("art-series"),
  cn: seriesImages("chinese-style"),
  modern: seriesImages("modern-tile"),
  wood: seriesImages("wood-grain"),
};

/** Generates image + gallery for one SKU based on series + index within the series.
 *  The 6 SKUs in each series rotate through 6 different main images. */
function pick(s: ReturnType<typeof seriesImages>, idx: number) {
  const cycle = [
    { image: s.texture, gallery: [s.space, s.banner, s.enter] },
    { image: s.space, gallery: [s.texture, s.banner, s.mBanner] },
    { image: s.banner, gallery: [s.texture, s.space, s.enter] },
    { image: s.enter, gallery: [s.texture, s.space, s.banner] },
    { image: s.mBanner, gallery: [s.texture, s.space, s.enter] },
    { image: s.mEnter, gallery: [s.texture, s.space, s.banner] },
  ];
  return cycle[idx % cycle.length];
}

