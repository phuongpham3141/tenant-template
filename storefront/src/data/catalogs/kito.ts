/**
 * Catalog KITO — 36 SKU đại diện trên 6 series.
 *
 * Nguồn ảnh: 100% từ CDN chính thức kito.cn — endpoint
 *   https://www.kito.cn/kitocms/webapi/at/getProductSeries
 * trả về 6 image asset đại diện cho mỗi series (banner, enter, space,
 * texture, m-banner, m-enter). Toàn bộ tải về tự host trong
 *   /img/products/kito/{series-slug}-{kind}.{ext}
 *
 * **Lưu ý quan trọng:** SPA `kito.cn/product.html` không phơi bày API
 * cho từng SKU riêng — chỉ trả series. Do đó:
 *   • Tên series + tagline (define): từ KITO API (đúng 100%)
 *   • Ảnh banner/enter/space/texture mỗi series: từ KITO API (thật)
 *   • Mã SKU + tên SKU + thông số: tổng hợp từ catalog KITO công bố
 *     trên Tmall/JD + hiểu biết ngành ceramic; mỗi SKU trong series
 *     dùng ảnh series rotated làm thumbnail (gallery có 3 góc nhìn khác
 *     nhau — texture, không gian, banner).
 *
 * Khi sourcing Quảng Châu lấy được catalog PDF KITO với ảnh từng SKU
 * riêng, swap field `image` + `gallery` ở mỗi entry.
 */

/** Helper xếp ảnh cho 1 series — 6 SKU rotated qua 4 view chính. */
function seriesImages(slug: string) {
  const base = `/img/products/kito/${slug}`;
  // Detect texture extension (wood-grain dùng .jpg, các series khác dùng .png)
  const textureExt = slug === "wood-grain" ? "jpg" : "png";
  return {
    texture: `${base}-texture.${textureExt}`,
    space: `${base}-space.png`,
    banner: `${base}-banner.jpg`,
    enter: `${base}-enter.jpg`,
    mBanner: `${base}-m-banner.jpg`,
    mEnter: `${base}-m-enter.${slug === "classic-candy" || slug === "stone-glaze" ? "jpg" : "png"}`,
  };
}

const IMG = {
  candy: seriesImages("classic-candy"),
  stone: seriesImages("stone-glaze"),
  art: seriesImages("art-series"),
  cn: seriesImages("chinese-style"),
  modern: seriesImages("modern-tile"),
  wood: seriesImages("wood-grain"),
};

/** Sinh image + gallery cho 1 SKU dựa trên series + chỉ số trong series.
 *  6 SKU mỗi series xoay vòng qua 6 ảnh chính khác nhau. */
function pick(s: ReturnType<typeof seriesImages>, idx: number) {
  const cycle = [
    { image: s.texture, gallery: [s.space, s.banner, s.enter] },
    { image: s.space, gallery: [s.texture, s.banner, s.mBanner] },
    { image: s.banner, gallery: [s.texture, s.space, s.enter] },
    { image: s.enter, gallery: [s.texture, s.space, s.banner] },
    { image: s.mBanner, gallery: [s.texture, s.space, s.enter] },
    { image: s.mEnter, gallery: [s.texture, s.space, s.banner] },
  ];
  return cycle[idx % cycle.length];
}

